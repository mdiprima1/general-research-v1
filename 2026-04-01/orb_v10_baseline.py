    def on_data(self, data):
        if self.is_warming_up:
            return

        # Update VIX
        if data.contains_key(self._vix):
            self._current_vix = data[self._vix].value
            self._prev_vix_10d.append(self._current_vix)
            if len(self._prev_vix_10d) > 15:
                self._prev_vix_10d = self._prev_vix_10d[-15:]

        self._handle_rollovers()

        spy_price = self.securities[self._spy].price
        if spy_price > 0:
            if self._spy_start_price is None:
                self._spy_start_price = spy_price
            self.plot("Strategy Equity", "SPY Buy & Hold",
                      self._initial_capital * (spy_price / self._spy_start_price))

        now = self.time
        if now.weekday() == 0:
            return

        # Dual vol filter
        if self.use_dual_vol_filter and self._vol_skip_today:
            return

        # Novel regime filters
        if self._filter_skip_today:
            return

        # Adaptive range: compute dynamic range filter bounds
        adaptive_min_range = self.min_range_pct
        adaptive_max_range = self.max_range_pct
        if self.use_adaptive_range:
            try:
                h = self.history(self._spy, self.adaptive_atr_period + 5, Resolution.DAILY)
                if not h.empty and len(h) >= self.adaptive_atr_period:
                    highs = h["high"].values if "high" in h.columns else h["close"].values
                    lows = h["low"].values if "low" in h.columns else h["close"].values
                    atrs = highs - lows
                    atr_pctile = float(np.percentile(atrs[-self.adaptive_atr_period:], 50))
                    mid_price = float(h["close"].values[-1])
                    if mid_price > 0:
                        adaptive_min_range = max(0.0005, atr_pctile / mid_price * 0.3)
                        adaptive_max_range = min(0.025, atr_pctile / mid_price * 3.0)
            except:
                pass

        for s, future in self.futures.items():
            key = self.symbol_keys[s]
            cfg = self.instrument_configs[key]
            state = self.daily_state[key]
            mapped = self.current_contracts.get(s)
            if mapped is None:
                continue

            price = self.securities[mapped].price
            if price <= 0:
                continue

            range_start = now.replace(hour=cfg["range_start_hour"], minute=cfg["range_start_min"], second=0)
            range_end = now.replace(hour=cfg["range_end_hour"], minute=cfg["range_end_min"], second=0)

            if range_start <= now < range_end and not state["range_set"]:
                state["collecting"] = True
                if state["range_high"] is None or price > state["range_high"]:
                    state["range_high"] = price
                if state["range_low"] is None or price < state["range_low"]:
                    state["range_low"] = price
                continue

            if state["collecting"] and now >= range_end and not state["range_set"]:
                state["collecting"] = False
                state["range_set"] = True
                rh, rl = state["range_high"], state["range_low"]
                if rh and rl and rh > rl:
                    range_pct = (rh - rl) / ((rh + rl) / 2)
                    min_r = adaptive_min_range if self.use_adaptive_range else self.min_range_pct
                    max_r = adaptive_max_range if self.use_adaptive_range else self.max_range_pct
                    if range_pct < min_r or range_pct > max_r:
                        state["traded_today"] = True
                else:
                    state["traded_today"] = True

            if not state["range_set"] or state["traded_today"]:
                continue

            flatten_time = now.replace(hour=cfg["flatten_hour"], minute=cfg["flatten_min"], second=0)
            if now >= flatten_time - timedelta(minutes=30):
                if state["direction"]:
                    self._check_exit(key, price, mapped)
                continue

            rh, rl = state["range_high"], state["range_low"]
            range_width = rh - rl

            if state["direction"] is None:
                if state["breakout_direction"]:
                    elapsed = (now - state["breakout_start_time"]).total_seconds() / 60
                    still_valid = (
                        (state["breakout_direction"] == "long" and price > rh) or
                        (state["breakout_direction"] == "short" and price < rl)
                    )
                    if not still_valid:
                        state["breakout_direction"] = None
                        state["breakout_start_time"] = None
                    elif elapsed >= self.confirmation_minutes:
                        qty = self._calc_position_size(mapped, range_width, cfg)
                        if qty > 0:
                            if state["breakout_direction"] == "long":
                                self.market_order(mapped, qty, tag=f"{key} LONG")
                                state["direction"] = "long"
                                state["entry_price"] = price
                                state["stop_price"] = rl
                                state["target_price"] = price + self.reward_risk_ratio * range_width
                            else:
                                self.market_order(mapped, -qty, tag=f"{key} SHORT")
                                state["direction"] = "short"
                                state["entry_price"] = price
                                state["stop_price"] = rh
                                state["target_price"] = price - self.reward_risk_ratio * range_width
                            state["traded_today"] = True
                            state["mapped_symbol"] = mapped
                        state["breakout_direction"] = None
                        state["breakout_start_time"] = None
                else:
                    trend = self._get_trend_direction(s, key)
                    if price > rh and trend >= 0:
                        state["breakout_direction"] = "long"
                        state["breakout_start_time"] = now
                    elif price < rl and trend <= 0:
                        state["breakout_direction"] = "short"
                        state["breakout_start_time"] = now
            elif state["direction"]:
                self._check_exit(key, price, mapped)

    def _check_exit(self, key, price, mapped):
        state = self.daily_state[key]
        if state["direction"] == "long":
            if price <= state["stop_price"] or price >= state["target_price"]:
                self.liquidate(mapped, tag=f"{key} EXIT")
                state["direction"] = None
        elif state["direction"] == "short":
            if price >= state["stop_price"] or price <= state["target_price"]:
                self.liquidate(mapped, tag=f"{key} EXIT")
                state["direction"] = None

    def _calc_position_size(self, mapped, range_width, cfg):
        sec = self.securities[mapped]
        mult = sec.symbol_properties.contract_multiplier
        if not mult or mult <= 0:
            mult = 1
        risk_per_contract = range_width * mult
        if risk_per_contract <= 0:
            return 0
        portfolio_value = self.portfolio.total_portfolio_value
        dollar_risk = portfolio_value * cfg["risk_per_trade"]
        target_qty = int(dollar_risk / risk_per_contract)
        return max(1, min(target_qty, self.max_contracts))

    def _flatten_all(self):
        for s in self.futures:
            key = self.symbol_keys[s]
            mapped = self.current_contracts.get(s)
            if mapped and self.portfolio[mapped].invested:
                self.liquidate(mapped, tag=f"{key} EOD flatten")
            self.daily_state[key]["direction"] = None

    def on_order_event(self, order_event):
        if order_event.status == OrderStatus.FILLED:
            year = self.time.year
            if year in self._year_trades:
                self._year_trades[year] += 1
            order = self.transactions.get_order_by_id(order_event.order_id)
            self.log(f"[ORDER] FILLED | {order_event.symbol} | "
                     f"qty={order_event.fill_quantity} @ {order_event.fill_price:.2f} | "
                     f"tag={order.tag if order else 'N/A'}")
