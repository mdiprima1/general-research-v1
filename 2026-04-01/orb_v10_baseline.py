    def _handle_rollovers(self):
        for s, future in self.futures.items():
            key = self.symbol_keys[s]
            mapped = future.mapped
            if mapped is None:
                continue
            prev = self._previous_contracts.get(s)
            self.current_contracts[s] = mapped
            if prev is not None and prev != mapped:
                if self.portfolio[prev].invested:
                    qty = self.portfolio[prev].quantity
                    self.liquidate(prev, tag=f"Roll out {key}")
                    self.market_order(mapped, qty, tag=f"Roll in {key}")
                    state = self.daily_state[key]
                    if state["mapped_symbol"] == prev:
                        state["mapped_symbol"] = mapped
            self._previous_contracts[s] = mapped

    def _get_trend_direction(self, symbol, key):
        today = self.time.date()
        if self._trend_cache_date != today:
            self._trend_cache = {}
            self._trend_cache_date = today
        if key in self._trend_cache:
            return self._trend_cache[key]
        try:
            h = self.history(symbol, self.sma_period + 5, Resolution.DAILY)
            if h.empty or len(h) < self.sma_period:
                direction = 0
            else:
                closes = h["close"].values
                sma_val = np.mean(closes[-self.sma_period:])
                direction = 1 if closes[-1] > sma_val else -1
        except:
            direction = 0
        self._trend_cache[key] = direction
        return direction

