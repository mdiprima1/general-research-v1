    def _check_all_filters(self):
        if self.is_warming_up:
            return

        self._vol_skip_today = False
        self._filter_skip_today = False

        # Dual vol filter
        if self.use_dual_vol_filter:
            vol_skip = False
            vix_skip = False
            try:
                h = self.history(self._spy, self.vol_lookback + 2, Resolution.DAILY)
                if not h.empty and len(h) >= self.vol_lookback:
                    closes = h["close"].values
                    rets = np.diff(closes) / closes[:-1]
                    realized_vol = float(np.std(rets[-self.vol_lookback:], ddof=1) * np.sqrt(252))
                    vol_skip = realized_vol < self.min_realized_vol

                    # ATR compression filter (uses same history)
                    if self.use_atr_compression:
                        daily_ranges = []
                        if len(h) >= 60:
                            highs = h["high"].values if "high" in h.columns else closes
                            lows = h["low"].values if "low" in h.columns else closes
                            daily_ranges = highs - lows
                            atr_5 = float(np.mean(daily_ranges[-5:]))
                            atr_60 = daily_ranges[-60:]
                            pctile_20 = float(np.percentile(atr_60, self.atr_pctile_threshold))
                            if atr_5 < pctile_20:
                                self._filter_skip_today = True
            except:
                pass

            if self._current_vix is not None:
                if self._current_vix < self.min_vix:
                    vix_skip = True

                # VIX compression proxy
                if self.use_vix_compression and len(self._prev_vix_10d) >= self.vix_drop_days:
                    vix_ago = self._prev_vix_10d[-self.vix_drop_days]
                    if vix_ago > 0:
                        vix_change = (self._current_vix - vix_ago) / vix_ago
                        if vix_change < -self.vix_drop_pct and self._current_vix < self.vix_compression_ceil:
                            self._filter_skip_today = True

            self._vol_skip_today = vol_skip or vix_skip

            year = self.time.year
            if self._vol_skip_today and year in self._vol_skip_count:
                self._vol_skip_count[year] += 1

        # Opening gap filter
        if self.use_opening_gap and not self._filter_skip_today:
            try:
                h = self.history(self._spy, 2, Resolution.DAILY)
                if not h.empty and len(h) >= 2:
                    prev_close = h["close"].values[-2]
                    today_open = h["open"].values[-1] if "open" in h.columns else h["close"].values[-1]
                    if prev_close > 0:
                        gap_pct = abs(today_open - prev_close) / prev_close
                        if gap_pct > self.max_gap_pct:
                            self._filter_skip_today = True
            except:
                pass

        # Overnight vol filter
        if self.use_overnight_vol and not self._filter_skip_today:
            for s, future in self.futures.items():
                key = self.symbol_keys[s]
                mapped = self.current_contracts.get(s)
                if mapped is None:
                    continue
                try:
                    h = self.history(mapped, 25, Resolution.DAILY)
                    if not h.empty and len(h) >= 21:
                        closes = h["close"].values
                        opens = h["open"].values if "open" in h.columns else closes
                        overnight_ranges = np.abs(opens[1:] - closes[:-1])
                        avg_20 = float(np.mean(overnight_ranges[-20:]))
                        current_overnight = float(overnight_ranges[-1]) if len(overnight_ranges) > 0 else 0
                        if avg_20 > 0 and current_overnight > self.overnight_vol_mult * avg_20:
                            self._filter_skip_today = True
                            break
                except:
                    pass

        # ML regime filter
        if self.use_ml_filter and self.ml_coefficients and not self._filter_skip_today:
            try:
                h = self.history(self._spy, 25, Resolution.DAILY)
                if not h.empty and len(h) >= 21:
                    closes = h["close"].values
                    rets = np.diff(closes) / closes[:-1]
                    realized_vol = float(np.std(rets[-20:], ddof=1) * np.sqrt(252))
                    spy_return_20d = float((closes[-1] / closes[-21] - 1.0)) if closes[-21] > 0 else 0.0

                    vix_val = self._current_vix if self._current_vix else 20.0
                    vix_change_5d = 0.0
                    if len(self._prev_vix_10d) >= 5:
                        vix_5d_ago = self._prev_vix_10d[-5]
                        if vix_5d_ago > 0:
                            vix_change_5d = (vix_val - vix_5d_ago) / vix_5d_ago

                    features = [realized_vol, vix_val, vix_change_5d, spy_return_20d]
                    coeffs = self.ml_coefficients
                    intercept = self.ml_intercept

                    # Logistic regression: sigmoid(intercept + sum(coeff_i * feature_i))
                    z = intercept
                    for feat, coeff in zip(features, [coeffs.get("realized_vol", 0),
                                                       coeffs.get("vix", 0),
                                                       coeffs.get("vix_change_5d", 0),
                                                       coeffs.get("spy_return_20d", 0)]):
                        z += feat * coeff
                    prob = 1.0 / (1.0 + np.exp(-z))
                    if prob < 0.5:
                        self._filter_skip_today = True
            except:
                pass

